UPDATE contracts
SET financial_profile_id = (SELECT id FROM financial_profiles WHERE is_default = TRUE);

UPDATE transaction_templates
SET financial_profile_id = (SELECT id FROM financial_profiles WHERE is_default = TRUE);

UPDATE transaction_materializations materialization
SET financial_profile_id = template.financial_profile_id
FROM transaction_templates template
WHERE template.id = materialization.transaction_template_id;

