CREATE TABLE financial_profiles (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    description TEXT NULL,
    kind VARCHAR(32) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at BIGINT NOT NULL,
    CONSTRAINT ck_financial_profiles_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_financial_profiles_kind CHECK (kind IN ('PERSON', 'GROUP'))
);

CREATE UNIQUE INDEX uq_financial_profiles_normalized_name
    ON financial_profiles (LOWER(BTRIM(name)));

CREATE UNIQUE INDEX uq_financial_profiles_single_default
    ON financial_profiles (is_default)
    WHERE is_default = TRUE;

